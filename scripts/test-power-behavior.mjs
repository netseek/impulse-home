import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const html = fs.readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const script = html.match(/<script type="text\/x-dc" data-dc-script>([\s\S]*?)<\/script>/)[1];
const context = vm.createContext({ DCLogic: class {}, window: {}, performance, console, setTimeout, clearTimeout });
vm.runInContext(script + ';globalThis.PowerComponent=Component;globalThis.signals=CAR_SIGNALS;', context);
const app = Object.create(context.PowerComponent.prototype);
const keys = context.signals;
app.state = {};
app._powerLive = {};
app._carSignalAt = {};
app._demoPreview = false;
let now = Date.now();
const publish = (key, field, value, age = 0) => {
  app._carSignalAt[key] = now - age;
  app._powerLive[field] = String(value);
};
assert.equal(app._powerModel(1).stateKey, 'unavailable');
publish(keys.powerFlow, 'flow', 'v1|ev|0|1|0');
publish(keys.batterySoc, 'soc', 64);
publish(keys.batteryVoltage, 'voltage', 360);
publish(keys.batteryCurrent, 'current', -50);
let model = app._powerModel(1);
assert.equal(model.stateKey, 'live');
assert.equal(model.kw, '18.0', 'battery magnitude does not infer regeneration from current polarity');
assert.equal(model.tone, 'ev');
assert.equal(model.frontLabel, 'Driving');
assert.equal(model.rearLabel, 'Inactive', 'front-only packet must not invent AWD');
assert.equal(model.driveToken, '1,0,0');
publish(keys.powerFlow, 'flow', 'v1|regen|0|0|-1');
model = app._powerModel(1);
assert.equal(model.frontFlow, '');
assert.equal(model.rearFlow, 'regen');
publish(keys.powerFlow, 'flow', 'v1|idle|0|0|0');
assert.equal(app._powerModel(1).iceClass, '', 'idle does not imply engine running');
publish(keys.powerFlow, 'flow', 'v1|ev|0|1|1', 120010);
publish(keys.batterySoc, 'soc', 64, 120010);
model = app._powerModel(1);
assert.equal(model.stateKey, 'partial');
assert.equal(model.driveToken, '', 'expired flow cannot animate despite fresh electrical readings');
assert.equal(model.socNum, '—', 'expired SOC is not presented as current');
for (const raw of ['v1|unknown|0|1|1', 'v1|ev|x|1|0', 'v1|ev|0|1junk|0', 'v1|ev|0||0']) {
  assert.equal(app._powerUnpackFlow(raw), null, `invalid packet ${raw}`);
}
app._powerHistory = [];
app._recordPowerSample(now);
assert.equal(app._powerHistory.length, 1);
app._recordPowerSample(now + 100);
assert.equal(app._powerHistory.length, 1, 'unchanged signal timestamps cannot create history');
publish(keys.batteryCurrent, 'current', -60, 5000);
app._recordPowerSample(now);
assert.equal(app._powerHistory.length, 1, 'old current cannot pair with fresh voltage');
app._powerHistory = [{ at: now - 1000, kw: 12 }, { at: now - 700, kw: 15 }, { at: now - 65000, kw: 100 }];
let history = app._powerHistoryView(now, false);
assert.equal(history.powerHistoryPeak, '15.0');
assert.equal(history.powerHistoryCeiling, '20');
assert.match(history.powerHistoryPath, /L/);
app._powerHistory = [{ at: now - 5000, kw: 12 }, { at: now, kw: 15 }];
assert.equal((app._powerHistoryView(now, false).powerHistoryPath.match(/M/g) || []).length, 2, 'gaps must not be interpolated');
assert.equal(app._powerHistoryView(now + 61000, false).powerHistoryHasData, false);
const before = JSON.stringify(app._powerHistory);
assert.equal(app._powerHistoryView(now, true).powerHistoryLabel, 'Simulated example');
assert.equal(JSON.stringify(app._powerHistory), before, 'demo must never contaminate recorded history');
console.log('Power behavior: fresh/stale signals, independent axles, polarity, malformed packets and history gaps OK');
